                       HEAD_LST_FROOSH_USER2.DEPATMAN, INVO_LST_TAKHFIFAT2.NAME, INVO_LST_TAKHFIFAT2.SUMOFMEGHK, INVO_LST_TAKHFIFAT2.MABL, 
                       INVO_LST_TAKHFIFAT2.SumOfMABL_K, INVO_LST_TAKHFIFAT2.SHNAME, INVO_LST_TAKHFIFAT2.DEPNAME, INVO_LST_TAKHFIFAT2.TFP, 
                       INVO_LST_TAKHFIFAT2.TAKH, INVO_LST_TAKHFIFAT2.SIMBAA, HEAD_LST_FROOSH_USER2.MBAAs, HEAD_LST_FROOSH_USER2.TAKHFIFs
 FROM         dbo.HEAD_LST_FROOSH_USER2(@Forms___F_MENU_GOZARESH_FROOSH___USERR, @Forms___F_MENU_GOZARESH_FROOSH___SSHIFT, 
                       @Forms___F_MENU_GOZARESH_FROOSH___DEPART, @Forms___F_MENU_GOZARESH_FROOSH___DT1, @Forms___F_MENU_GOZARESH_FROOSH___DT2) 
