 (@Forms___F_MENU_GOZARESH_FROOSH___USERR nvarchar(40),
 @Forms___F_MENU_GOZARESH_FROOSH___SSHIFT NVARCHAR(10),
 @Forms___F_MENU_GOZARESH_FROOSH___DEPART INT,
 @Forms___F_MENU_GOZARESH_FROOSH___DT1 BIGINT,
 @Forms___F_MENU_GOZARESH_FROOSH___DT2 BIGINT)
 RETURNS TABLE
 AS
 RETURN ( SELECT     HEAD_LST_FROOSH_USER2.SumOfM_NAGHD, HEAD_LST_FROOSH_USER2.SumOfMABL_VAR, HEAD_LST_FROOSH_USER2.SumOfMABL_HAV, 
