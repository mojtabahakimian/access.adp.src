                       dbo.INVO_LST_TAKHFIFAT2(@Forms___F_MENU_GOZARESH_FROOSH___USERR, @Forms___F_MENU_GOZARESH_FROOSH___SSHIFT, 
                       @Forms___F_MENU_GOZARESH_FROOSH___DEPART, @Forms___F_MENU_GOZARESH_FROOSH___DT1, @Forms___F_MENU_GOZARESH_FROOSH___DT2) 
                       INVO_LST_TAKHFIFAT2 ON HEAD_LST_FROOSH_USER2.DEPATMAN = INVO_LST_TAKHFIFAT2.DEPATMAN AND 
                       HEAD_LST_FROOSH_USER2.SHIFT = INVO_LST_TAKHFIFAT2.SHIFT AND HEAD_LST_FROOSH_USER2.USER_NAME = INVO_LST_TAKHFIFAT2.USER_NAME )
